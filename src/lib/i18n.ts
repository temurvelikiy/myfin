// Xato kalitini (masalan "errAmount") tarjimaga aylantiradi; kalit bo'lmasa matnning o'zi qaytadi.
export function tMsg(t: Dict, msg: string) {
  const [key, arg] = msg.split("|");
  const v = (t as Record<string, unknown>)[key];
  if (typeof v !== "string") return msg;
  return arg === undefined ? v : v.replace("{v}", group(Number(arg)));
}

